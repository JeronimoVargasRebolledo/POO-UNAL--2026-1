# ejercicio 12: salario bruto, retencion y neto

horas = 48
valor_hora = 5000

# salario bruto
bruto = horas * valor_hora

# retencion del 12.5%
retencion = bruto * 0.125

salario_neto = bruto - retencion

print("Salario Bruto:", bruto)
print("Retencion:", retencion)
print("Salario Neto:", salario_neto)
